import assert from 'node:assert/strict';
import { discoverPlaywright, discoverBrowser } from './verify-art-history-browser.mjs';
const origin = process.env.ACCOUNT_TEST_ORIGIN || 'http://127.0.0.1:4174';
const playwright = await discoverPlaywright();
const executablePath = await discoverBrowser(playwright.chromium);
const browser = await playwright.chromium.launch({ executablePath, headless: true, args: ['--no-sandbox'] });
const reports = [];
try {
  for (const viewport of [{width:1440,height:1000},{width:375,height:812},{width:812,height:375}]) {
    const page = await browser.newPage({viewport, reducedMotion:'reduce'});
    const requests = [];
    page.on('request', req => requests.push(req.url()));
    await page.route('**/assets/auth/auth-config.mjs', route=>route.fulfill({contentType:'text/javascript',body:'export const AUTH_CONFIG={supabaseUrl:"",publishableKey:"",googleEnabled:false};'}));
    await page.goto(`${origin}/index.html`, {waitUntil:'domcontentloaded'});
    await page.locator('[data-account-trigger]').click();
    await page.getByRole('dialog').waitFor();
    assert.match(await page.locator('.account-status').textContent(), /暂未连接账号服务/);
    assert.equal(await page.locator('.account-submit').isDisabled(), true);
    assert.equal(requests.some(url=>/supabase|google.*oauth/i.test(url)), false);
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
    if(viewport.width===1440 || viewport.width===375) await page.screenshot({path:viewport.width===1440?'/tmp/account-desktop.png':'/tmp/account-mobile.png'});
    await page.keyboard.press('Tab');
    assert.equal(await page.evaluate(()=>Boolean(document.activeElement.closest('.account-dialog'))),true);
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('[data-account-trigger]').evaluate(el=>el===document.activeElement),true);
    if(viewport.width===1440){
      await page.locator('[data-subj="art"]').click();
      await page.locator('.map-card[data-subject="art"]').waitFor();
      assert.ok(await page.locator('iframe[src*="art-history-map"]').count());
      await page.locator('[data-subj="world"]').click();
      await page.locator('.map-card[data-subject="world"]').waitFor();
    }
    await page.close();

    const ui = await browser.newPage({viewport,reducedMotion:'reduce'});
    await ui.route('**/account-test-harness.html', route=>route.fulfill({contentType:'text/html',body:'<!doctype html><meta name="viewport" content="width=device-width,initial-scale=1"><link rel="stylesheet" href="/assets/auth/account.css"><button data-account-trigger>登录 / 注册</button>'}));
    await ui.goto(`${origin}/account-test-harness.html`);
    await ui.evaluate(async()=>{
      const {mountAccountUI}=await import('/assets/auth/account-ui.mjs');
      let state={status:'loading',user:null,recovery:false,message:''};
      const listeners=new Set();
      const publish=next=>{state={...state,...next};for(const fn of listeners)fn(state);};
      window.calls=[];
      window.publishAccount=publish;
      window.result={ok:false,code:'login-failed',message:'邮箱或密码不正确。'};
      const action=async(name,fields)=>{window.calls.push({name,fields});if(window.hold)await new Promise(resolve=>window.releaseAccount=resolve);return window.result;};
      window.accountTest=mountAccountUI({document,googleEnabled:true,service:{getState:()=>state,subscribe(fn){listeners.add(fn);fn(state);return()=>listeners.delete(fn);},signIn:fields=>action('signIn',fields),signUp:fields=>action('signUp',fields),requestPasswordReset:fields=>action('forgot',fields),updatePassword:fields=>action('update',fields),signInGoogle:()=>action('google'),signOut:async()=>{publish({status:'guest',user:null});return {ok:true,code:'signed-out',message:'已退出登录。'};}}});
    });
    await ui.locator('[data-account-trigger]').click();
    assert.match(await ui.locator('.account-status').textContent(), /正在连接/);
    await ui.evaluate(()=>window.publishAccount({status:'guest',message:''}));
    assert.equal(await ui.locator('.account-status').textContent(),'','connection status must clear when initialization finishes');
    await ui.getByLabel('电子邮箱',{exact:true}).fill('bad');
    await ui.getByLabel('密码',{exact:true}).focus();
    assert.match(await ui.locator('#account-email-error').textContent(), /有效/);
    await ui.getByLabel('电子邮箱',{exact:true}).fill('learner@example.com');
    await ui.getByLabel('密码',{exact:true}).fill('correct-password');
    await ui.getByRole('button',{name:'显示密码',exact:true}).click();
    assert.equal(await ui.locator('#account-password').getAttribute('type'),'text');
    await ui.getByRole('button',{name:'隐藏密码',exact:true}).click();
    await ui.locator('.account-submit').click();
    await ui.getByRole('status').filter({hasText:'邮箱或密码不正确'}).waitFor();
    await ui.getByRole('tab',{name:'注册',exact:true}).click();
    await ui.getByLabel('密码',{exact:true}).fill('correct-password');
    await ui.getByLabel('确认密码',{exact:true}).fill('different-password');
    await ui.locator('.account-submit').click();
    assert.match(await ui.locator('#account-confirm-error').textContent(), /不一致/);
    await ui.getByLabel('确认密码',{exact:true}).fill('correct-password');
    await ui.evaluate(()=>{window.result={ok:true,code:'confirmation-required',message:'请查看邮箱中的验证邮件。'};window.hold=true;});
    await ui.locator('.account-submit').click();
    assert.equal(await ui.locator('.account-submit').isDisabled(),true, JSON.stringify(await ui.evaluate(()=>({status:document.querySelector('.account-status').textContent,errors:[...document.querySelectorAll('.account-field-error')].map(el=>el.textContent),calls:window.calls,hold:window.hold}))));
    await ui.evaluate(()=>document.querySelector('.account-form').requestSubmit());
    assert.equal(await ui.evaluate(()=>window.calls.filter(c=>c.name==='signUp').length),1);
    await ui.evaluate(()=>{window.hold=false;window.releaseAccount();});
    await ui.getByRole('status').filter({hasText:'验证邮件'}).waitFor();
    await ui.getByRole('button',{name:'忘记密码？',exact:true}).click();
    await ui.evaluate(()=>window.result={ok:true,code:'reset-email-sent',message:'如果该邮箱已注册，你将收到密码重置邮件。'});
    await ui.locator('.account-submit').click();
    await ui.getByRole('status').filter({hasText:'如果该邮箱已注册'}).waitFor();
    await ui.evaluate(()=>window.publishAccount({status:'authenticated',user:{id:'u',email:'<img src=x onerror=alert(1)>'},recovery:false}));
    assert.equal(await ui.locator('.account-user').textContent(),'<img src=x onerror=alert(1)>');
    assert.equal(await ui.locator('.account-user img').count(),0);
    await ui.getByRole('button',{name:'退出登录',exact:true}).click();
    await ui.getByRole('status').filter({hasText:'已退出登录'}).waitFor();
    await ui.evaluate(()=>window.publishAccount({status:'recovery',user:{id:'u',email:'learner@example.com'},recovery:true}));
    await ui.getByLabel('密码',{exact:true}).fill('new-correct-password');
    await ui.getByLabel('确认密码',{exact:true}).fill('new-correct-password');
    await ui.evaluate(()=>window.result={ok:true,code:'password-updated',message:'密码已更新。'});
    await ui.locator('.account-submit').click();
    await ui.getByRole('status').filter({hasText:'密码已更新'}).waitFor();
    const bounds=await ui.getByRole('dialog').boundingBox();
    assert.ok(bounds.x>=0&&bounds.x+bounds.width<=viewport.width+1);
    assert.equal(await ui.locator('#account-password').evaluate(el=>parseFloat(getComputedStyle(el).fontSize)>=16),true);
    await ui.keyboard.press('Escape');
    assert.equal(await ui.locator('#account-password').inputValue(),'');
    assert.equal(await ui.locator('[data-account-trigger]').evaluate(el=>el===document.activeElement),true);
    await ui.evaluate(()=>window.publishAccount({status:'guest',user:null,recovery:false}));
    await ui.locator('[data-account-trigger]').click();
    await ui.getByLabel('密码',{exact:true}).fill('correct-password');
    await ui.evaluate(()=>{window.hold=true;window.result={ok:true,code:'authenticated',message:'账户验证成功。'};});
    await ui.locator('.account-submit').click();
    await ui.keyboard.press('Escape');
    await ui.locator('[data-account-trigger]').click();
    assert.equal(await ui.locator('.account-submit').isDisabled(),true,'closing must not permit overlapping auth requests');
    await ui.keyboard.press('Escape');
    await ui.evaluate(()=>{window.hold=false;window.releaseAccount();window.publishAccount({status:'authenticated',user:{id:'u',email:'learner@example.com'},recovery:false});});
    assert.equal(await ui.getByRole('dialog').isVisible(),false);
    assert.equal(await ui.locator('#account-password').inputValue(),'');
    assert.equal(await ui.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
    reports.push({viewport,passed:true});
    await ui.close();
  }
  const callback=await browser.newPage();
  await callback.route('**/assets/auth/auth-config.mjs',route=>route.fulfill({contentType:'text/javascript',body:'export const AUTH_CONFIG={supabaseUrl:"https://account-test.supabase.co",publishableKey:"sb_publishable_test",googleEnabled:false};'}));
  let scrubbedBeforeSDK=false;
  await callback.route('**/assets/vendor/supabase-js-2.118.0.js',async route=>{
    scrubbedBeforeSDK=!new URL(callback.url()).search&&!new URL(callback.url()).hash;
    await route.fulfill({contentType:'text/javascript',body:'window.supabase={createClient(){return {auth:{getUser:async()=>({data:{user:null}}),onAuthStateChange:()=>({data:{subscription:{unsubscribe(){}}}}),exchangeCodeForSession:async()=>({error:{message:"expired"}})}}}};'});
  });
  await callback.goto(`${origin}/auth-callback.html?code=expired&type=recovery&returnTo=https://evil.example/#access_token=forbidden`,{waitUntil:'domcontentloaded'});
  await callback.getByRole('status').filter({hasText:'验证链接无效'}).waitFor();
  assert.equal(scrubbedBeforeSDK,true);
  assert.equal(await callback.locator('[data-field="confirm"]').isVisible(),false);
  assert.equal(await callback.locator('.account-dialog .account-return').getAttribute('href'),`${origin}/index.html`);
  await callback.goto(`${origin}/auth-callback.html`,{waitUntil:'domcontentloaded'});
  await callback.getByRole('status').filter({hasText:'验证链接无效'}).waitFor();
  assert.equal(await callback.locator('.account-forgot').isVisible(),true);
  reports.push({callbackScrub:true,unprovenRecoveryBlocked:true,directCallbackActionable:true});
  await callback.close();
  console.log(JSON.stringify({ok:true,reports},null,2));
} finally {await browser.close();}
